export function matchVerifiedLegalReferences(query = '', mode = '') {
  const lower = `${query} ${mode}`.toLowerCase();
  const matched = [];

  for (const ref of VERIFIED_LEGAL_REFERENCES) {
    const hits = ref.keywords.filter(kw => lower.includes(kw)).length;
    if (
      hits > 0 ||
      (mode === 'company-advisor' && ref.id === 'companies-act-opc-llp-pvt-ltd') ||
      (mode === 'midcase-battle-card' && ref.id === 'cpa-2019-consumer-fees-and-portals')
    ) {
      matched.push({ ...ref, score: hits + (mode === 'company-advisor' && ref.id === 'companies-act-opc-llp-pvt-ltd' ? 2 : 0) });
    }
  }

  if (matched.length === 0 && mode === 'messy-dump-intake') {
    matched.push({ ...VERIFIED_LEGAL_REFERENCES[1], score: 1 });
  }

  return matched.sort((a, b) => b.score - a.score).slice(0, 3);
}

function stripHtmlTags(html = '') {
  return String(html || '')
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Performs a fast, timeout-bounded live web search prioritizing Indian government/legal sources.
 * Gracefully returns [] if offline, disabled, or running inside mocked test environments.
 */
export async function searchOfficialLegalWeb(rawQuery = '', { timeoutMs = 2800, fetchImpl = globalThis.fetch } = {}) {
  const cleanQuery = String(rawQuery || '')
    .split('ATTACHED FOLDER / TEXT DOCUMENTS:')[0]
    .replace(/User Role:.*?\n/gi, '')
    .replace(/Need Type:.*?\n/gi, '')
    .replace(/Raw Story \/ WhatsApp Chat:/gi, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 180);

  if (!cleanQuery || cleanQuery.length < 8) return [];
  if (process.env.NYAYA_DISABLE_WEB_SEARCH === '1' || process.env.LLM_PROVIDER === 'openai') {
    return [];
  }

  try {
    const searchTerms = `${cleanQuery} India law official gov.in`;
    const url = `https://html.duckduckgo.com/html/?q=${encodeURIComponent(searchTerms)}`;
    const res = await fetchImpl(url, {
      method: 'GET',
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
        'Accept': 'text/html'
      },
      signal: AbortSignal.timeout(timeoutMs)
    });
    if (!res.ok) return [];
    const html = await res.text();
    const results = [];
    const blockRegex = /<a[^>]*class="result__a"[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>[\s\S]*?<a[^>]*class="result__snippet"[^>]*>([\s\S]*?)<\/a>/gi;
    let match;
    while ((match = blockRegex.exec(html)) !== null && results.length < 4) {
      let href = match[1] || '';
      const uddgMatch = href.match(/[?&]uddg=([^&]+)/);
      if (uddgMatch) {
        try {
          href = decodeURIComponent(uddgMatch[1]);
        } catch {
          // keep original
        }
      }
      const title = stripHtmlTags(match[2]);
      const snippet = stripHtmlTags(match[3]);
      if (title && snippet) {
        results.push({ title, url: href, snippet });
      }
    }
    return results;
  } catch {
    return [];
  }
}

export async function buildGroundedLegalContext(rawQuery = '', mode = '', options = {}) {
  const verifiedRefs = matchVerifiedLegalReferences(rawQuery, mode);
  const webResults = await searchOfficialLegalWeb(rawQuery, options);

  const sections = [];
  if (verifiedRefs.length > 0) {
    sections.push(
      'VERIFIED INDIAN STATUTORY & OFFICIAL PORTAL REFERENCE PACK (Authoritative — safe to quote directly):\n' +
      verifiedRefs.map(r => `### ${r.title}\n${r.summary}`).join('\n\n')
    );
  }
  if (webResults.length > 0) {
    sections.push(
      'LIVE WEB & OFFICIAL PORTAL SEARCH RESULTS:\n' +
      webResults.map((w, i) => `${i + 1}. ${w.title} (${w.url})\n   Snippet: ${w.snippet}`).join('\n')
    );
  }
  return {
    verifiedRefs,
    webResults,
    contextBlock: sections.join('\n\n') || '(No additional statutory pack matched.)'
  };
}
